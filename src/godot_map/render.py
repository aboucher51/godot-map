"""Render a scanned project as the Markdown summary and the JSON graph.

The Markdown is the *always-read* tier: short enough to sit in an agent's
context at the start of a task, with the questions that otherwise cost a
grep through every scene — which scenes carry which scripts, who instances
whom, how the autoload signals are wired, what nothing references. The
JSON is the *query* tier with every node and edge.
"""

from __future__ import annotations

import json
import os
import re

from .query import problems
from .scan import Project

_MAX_USERS = 6  # "used by" cells longer than this show a count
_MAX_PROBLEMS = 30


def _short(path: str) -> str:
    return path[len("res://"):] if path.startswith("res://") else path


def _link(path: str) -> str:
    return f"`{_short(path)}`"


def _tree(project: Project, path: str) -> str:
    """A node tree for one scene, `Name:Type` per line, instances and scripts noted."""
    scene = project.scenes[path]
    lines = []
    for node in scene.nodes:
        depth = 0 if node.path == "." else node.path.count("/") + 1
        indent = "  " * depth
        label = node.name if node.type is None else f"{node.name}:{node.type}"
        extras = []
        if node.instance:
            extras.append(f"← {_short(node.instance)}")
        if node.script:
            extras.append(f"[{_short(node.script)}]")
        if node.groups:
            extras.append("groups=" + ",".join(node.groups))
        lines.append(f"{indent}{label}" + (("  " + " ".join(extras)) if extras else ""))
    return "\n".join(lines)


def _is_test(path: str) -> bool:
    return path.startswith("res://tests/") or path.startswith("res://test/")


def _users_cell(users: list[str]) -> str:
    """Users as a short cell: tests are counted, not listed, so they do not crowd out the real ones."""
    real = [u for u in users if not _is_test(u)]
    tests = len(users) - len(real)
    shown = [u.split(":", 1)[1] if u.startswith("autoload:") else _short(u) for u in real]
    if len(shown) > _MAX_USERS:
        shown = shown[: _MAX_USERS - 2] + [f"+{len(shown) - _MAX_USERS + 2} more"]
    if tests:
        shown.append(f"{tests} test{'s' if tests > 1 else ''}")
    return ", ".join(shown)


def render_markdown(
    project: Project, *, trees: bool = True, max_tree_nodes: int = 40, mermaid: bool = False
) -> str:
    out: list[str] = []
    name = project.name or _short(project.root)
    out.append(f"# Project map: {name}\n")
    out.append("Generated by `godot-map`; do not edit. Regenerate with `godot-map .` after adding or moving scenes or scripts.\n")
    counts = (
        f"{len(project.scenes)} scenes, {len(project.scripts)} scripts, "
        f"{len(project.resources)} resources, {len(project.autoloads)} autoloads"
    )
    out.append(f"{counts}.")
    if project.main_scene:
        out.append(f"Main scene: {_link(project.main_scene)}.")
    if project.features:
        out.append("Features: " + ", ".join(project.features) + ".")
    out.append("")

    # Autoloads
    if project.autoloads:
        out.append("## Autoloads (in load order)\n")
        out.append("| Name | Script | class_name | Signals |")
        out.append("|---|---|---|---|")
        for aname, path in project.autoloads.items():
            script = project.scripts.get(path)
            cls = script.class_name if script and script.class_name else ""
            sigs = ", ".join(script.signals) if script else ""
            out.append(f"| {aname} | {_link(path)} | {cls} | {sigs} |")
        out.append("")

    # Signal wiring: every signal a project script declares, with its
    # emitters and its listeners from code and from scene [connection]s.
    wiring = signal_wiring(project)
    if wiring:
        out.append("## Signal wiring\n")
        out.append(
            "Every `signal` a project script declares that something listens to, or that another script emits. "
            "Code listeners are `X.sig.connect(`; scene listeners are `[connection]` blocks, "
            "as `scene: from → to.method`. Engine signals (`pressed`, `body_entered`) are under each scene.\n"
        )
        out.append("| Signal | Declared in | Emitted in | Connected in code | Connected in scenes |")
        out.append("|---|---|---|---|---|")
        for row in wiring:
            out.append(
                f"| {row['signal']} | {', '.join(_link(p) for p in row['declared_in'])} | "
                f"{', '.join(_link(p) for p in row['emitted_in']) or '—'} | "
                f"{', '.join(_link(p) for p in row['connected_in_code']) or '—'} | "
                f"{', '.join(row['connected_in_scenes']) or '—'} |"
            )
        out.append("")

    # Scenes
    if project.scenes:
        out.append("## Scenes\n")
        for path, scene in sorted(project.scenes.items()):
            root = scene.root
            head = f"### {_link(path)}"
            if root:
                head += f" — {root.name}:{root.type or '?'}"
            out.append(head + "\n")
            facts = []
            if scene.inherits:
                facts.append(f"inherits {_link(scene.inherits)}")
            facts.append(f"{len(scene.nodes)} nodes")
            if scene.scripts:
                facts.append("scripts: " + ", ".join(_link(s) for s in scene.scripts))
            if scene.instances:
                facts.append("instances: " + ", ".join(_link(s) for s in scene.instances))
            users = [u for u in project.used_by.get(path, []) if not u.startswith("autoload:")]
            if users:
                facts.append("used by: " + _users_cell(users))
            out.append("; ".join(facts) + ".")
            if scene.connections:
                out.append("")
                out.append("Connections:")
                for c in scene.connections:
                    out.append(f"- `{c.from_node}` {c.signal} → `{c.to_node}`.{c.method}()")
            if trees and len(scene.nodes) <= max_tree_nodes:
                out.append("")
                out.append("```")
                out.append(_tree(project, path))
                out.append("```")
            elif trees:
                out.append(f"\n(tree omitted: {len(scene.nodes)} nodes; see the JSON)")
            out.append("")

    # Classes
    if project.classes:
        out.append("## class_name index\n")
        out.append("| Class | Script | extends | Signals |")
        out.append("|---|---|---|---|")
        for cls, path in sorted(project.classes.items()):
            s = project.scripts[path]
            out.append(f"| {cls} | {_link(path)} | {s.extends or ''} | {', '.join(s.signals)} |")
        out.append("")

    # Scripts not attached anywhere
    loose = [
        p
        for p, s in sorted(project.scripts.items())
        if not s.class_name and not _is_test(p)
        and all(_is_test(u) for u in project.used_by.get(p, []))
    ]
    if loose:
        out.append("## Scripts nothing references\n")
        out.append("No scene attaches them, no autoload names them, no script loads, extends or names them, and they declare no class_name. Entry points, dead code, or loaded by a path built at runtime.\n")
        for p in loose:
            tests = len(project.used_by.get(p, []))
            out.append(f"- {_link(p)}" + (f" (only {tests} test script{'s' if tests > 1 else ''})" if tests else ""))
        out.append("")

    # Groups
    if project.groups:
        out.append("## Groups\n")
        out.append("Membership from scenes and `add_to_group`; queries are `get_nodes_in_group`, `call_group`, `is_in_group`.\n")
        out.append("| Group | In scenes | Joined in code | Queried in code |")
        out.append("|---|---|---|---|")
        for name, g in sorted(project.groups.items()):
            scenes = []
            for spath, nodes in sorted(g["scenes"].items()):
                names = nodes if len(nodes) <= 3 else nodes[:2] + [f"+{len(nodes) - 2}"]
                scenes.append(f"`{_short(spath)}`: {', '.join(names)}")
            out.append(
                f"| {name} | {'; '.join(scenes) or '—'} | {_users_cell(g['joined_in']) or '—'} | "
                f"{_users_cell(g['queried_in']) or '—'} |"
            )
        out.append("")

    # Scripts index (compact); test scripts are counted, not listed
    tests = sorted(p for p in project.scripts if p.startswith("res://tests/"))
    if project.scripts:
        out.append("## Scripts\n")
        if tests:
            out.append(f"{len(tests)} test script{'s' if len(tests) > 1 else ''} under `tests/` {'are' if len(tests) > 1 else 'is'} not listed.\n")
        out.append("| Script | extends | class_name | attached in / used by | signals | funcs |")
        out.append("|---|---|---|---|---|---|")
        for path, s in sorted(project.scripts.items()):
            if path in tests:
                continue
            cls = s.class_name or ""
            if cls and not s.is_global:
                cls += " (C#, not global)"
            out.append(
                f"| {_link(path)} | {s.extends or ''} | {cls} | {_users_cell(project.used_by.get(path, []))} | "
                f"{len(s.signals)} | {len(s.funcs)} |"
            )
        out.append("")

    # Data files: a count, and the directories holding files nothing names.
    if project.data:
        out.append("## Data files\n")
        loose_dirs: dict[str, int] = {}
        for p in project.data:
            if p not in project.used_by:
                parts = _short(p).split("/")[:-1]
                d = "/".join(parts[:2]) + "/" if parts else "./"
                loose_dirs[d] = loose_dirs.get(d, 0) + 1
        line = f"{len(project.data)} `.json`/`.csv`/`.gdshader` files; each one's users are under `data` in the JSON."
        if loose_dirs:
            line += " Named by no scene, resource or script literal (loaded by a built path, or unused): " + ", ".join(
                f"`{d}` ({n})" for d, n in sorted(loose_dirs.items())
            ) + "."
        out.append(line)
        out.append("")

    # Problems: what the engine would report on load, found statically.
    found = problems(project)
    if found:
        out.append("## Problems\n")
        out.append("Found by `godot-map . --problems`: `res://` references that name nothing on disk, signals emitted or connected that the target does not declare, scene connections to a method the script lacks.\n")
        for pr in found[:_MAX_PROBLEMS]:
            out.append(f"- `{_short(pr.source)}`: {pr.detail}")
        if len(found) > _MAX_PROBLEMS:
            out.append(f"- ... {len(found) - _MAX_PROBLEMS} more")
        out.append("")

    if mermaid and project.scenes:
        out.append("## Scene graph\n")
        out.append("```mermaid")
        out.extend(_mermaid(project))
        out.append("```")
        out.append("")

    return "\n".join(out).rstrip() + "\n"


def _mermaid(project: Project) -> list[str]:
    """A scene-instance graph: every scene a node, every instance an edge."""
    ids: dict[str, str] = {}
    for path in sorted(project.scenes):
        ids[path] = "s" + re.sub(r"\W", "_", _short(path))
    lines = ["graph LR"]
    for path in sorted(project.scenes):
        label = _short(path)
        lines.append(f'  {ids[path]}["{label}"]' + (":::main" if path == project.main_scene else ""))
    for path, scene in sorted(project.scenes.items()):
        for inst in scene.instances:
            if inst in ids:
                lines.append(f"  {ids[path]} --> {ids[inst]}")
        if scene.inherits and scene.inherits in ids:
            lines.append(f"  {ids[path]} -.->|inherits| {ids[scene.inherits]}")
    if project.main_scene in ids:
        lines.append("  classDef main stroke-width:3px")
    return lines


def signal_wiring(project: Project, *, all_rows: bool = False) -> list[dict]:
    """One row per declared signal that something emits or listens to.

    Autoload signals are keyed ``Autoload.sig`` and matched on that exact
    target. Every other declared signal is keyed by name and matched on the
    last segment of an emit/connect target (``enemy.died.connect(`` and a
    bare ``died.emit(`` both count), so a name declared by two classes is
    one row naming both."""
    autoload_by_path = {p: n for n, p in project.autoloads.items()}
    rows: dict[str, dict] = {}

    def row(key: str) -> dict:
        return rows.setdefault(
            key,
            {"signal": key, "declared_in": [], "emitted_in": [], "connected_in_code": [], "connected_in_scenes": []},
        )

    named: dict[str, str] = {}  # bare signal name -> row key (non-autoload)
    for spath, s in sorted(project.scripts.items()):
        for sig in s.signals:
            if spath in autoload_by_path:
                row(f"{autoload_by_path[spath]}.{sig}")["declared_in"].append(spath)
            else:
                row(sig)["declared_in"].append(spath)
                named[sig] = sig
    autoload_keys = {k for k in rows if "." in k}
    for spath, s in sorted(project.scripts.items()):
        for col, targets in (("emitted_in", s.emits), ("connected_in_code", s.connects)):
            for target in targets:
                if target in autoload_keys:
                    key = target
                else:
                    name = target.rsplit(".", 1)[-1]
                    if name not in named:
                        continue
                    key = name
                    # a bare emit of an autoload's own signal, inside the autoload
                    if "." not in target and spath in autoload_by_path and f"{autoload_by_path[spath]}.{name}" in rows:
                        key = f"{autoload_by_path[spath]}.{name}"
                if spath not in rows[key][col]:
                    rows[key][col].append(spath)
    for scene_path, scene in sorted(project.scenes.items()):
        for c in scene.connections:
            if c.signal in named:
                rows[c.signal]["connected_in_scenes"].append(
                    f"`{_short(scene_path)}`: {c.from_node} → {c.to_node}.{c.method}"
                )
    # A signal only its own declarer emits, with no listener anywhere, is
    # already in the class index; it earns no row here.
    return [
        r for _, r in sorted(rows.items())
        if all_rows or r["connected_in_code"] or r["connected_in_scenes"]
        or any(e not in r["declared_in"] for e in r["emitted_in"])
    ]


def render_json(project: Project) -> str:
    return json.dumps(project.to_dict(), indent=1, sort_keys=False) + "\n"
